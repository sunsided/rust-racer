/// Declares the (stateless) data of each system and lets [`SystemFactory`] create it.
macro_rules! stateless_systems {
    ($($system:ident($data:ident)),* $(,)?) => {
        $(
            #[derive(Debug, Default)]
            pub struct $data;

            impl CreateSystem<$system> for SystemFactory {
                fn create(&self) -> $system {
                    $system::from($data)
                }
            }
        )*
    };
}

/// Builds the system instances for the world.
pub struct SystemFactory;

stateless_systems! {
    TrafficSystem(TrafficSystemData),
    TrafficIndexSystem(TrafficIndexSystemData),
    DrivingSystem(DrivingSystemData),
    CollisionSystem(CollisionSystemData),
    LapTimerSystem(LapTimerSystemData),
    ParallaxSystem(ParallaxSystemData),
    SnapshotSystem(SnapshotSystemData),
}

impl ApplyTrafficSystem for TrafficSystem {
    type Error = Infallible;

    fn apply_many(
        &mut self,
        track: &TrackState,
        grid: &TrafficGridState,
        player: &PlayerViewState,
        speeds: &[SpeedComponent],
        car_models: &[CarModelComponent],
        track_positions: &mut [TrackPositionComponent],
    ) {
        let track_length = track.length();
        let ahead = Ahead {
            track,
            grid,
            player,
            player_segment: track.find(player.position + player_z()),
        };
        for ((speed, model), pos) in speeds.iter().zip(car_models).zip(track_positions) {
            let speed = **speed;
            let car_segment = track.find(pos.z);
            pos.offset += ahead.steer_around(car_segment, speed, pos.offset, model.w);
            pos.z = increase(pos.z, STEP * speed, track_length);
            pos.percent = percent_remaining(pos.z, SEGMENT_LENGTH);
        }
    }
}

/// What an AI car can see of the road ahead.
struct Ahead<'a> {
    track: &'a TrackState,
    grid: &'a TrafficGridState,
    player: &'a PlayerViewState,
    player_segment: usize,
}

impl Ahead<'_> {
    /// How far a car at `offset` swerves this step to get around slower cars (or the player)
    /// in the next few segments, or to get back onto the road.
    fn steer_around(&self, car_segment: usize, speed: f32, offset: f32, sprite_w: f32) -> f32 {
        const LOOKAHEAD: usize = 20;

        // Don't bother steering around other cars when out of sight of the player.
        if car_segment as isize - self.player_segment as isize > DRAW_DISTANCE as isize {
            return 0.0;
        }

        let player = self.player;
        let car_w = sprite_w * sprites::SCALE;
        let segments = self.track.len();
        for i in 1..LOOKAHEAD {
            let segment = (car_segment + i) % segments;

            // The closer the obstacle (smaller `i`) and the bigger the speed difference, the
            // harder the swerve.
            if segment == self.player_segment
                && speed > player.speed
                && overlap(player.x, PLAYER_W, offset, car_w, 1.2)
            {
                let dir = swerve_direction(offset, player.x);
                return dir / i as f32 * (speed - player.speed) / MAX_SPEED;
            }

            for other in self.grid.cars(segment) {
                if speed > other.speed && overlap(offset, car_w, other.offset, other.width(), 1.2) {
                    let dir = swerve_direction(offset, other.offset);
                    return dir / i as f32 * (speed - other.speed) / MAX_SPEED;
                }
            }
        }

        // No cars ahead, but somehow ended up off road: steer back on.
        if offset < -0.9 {
            0.1
        } else if offset > 0.9 {
            -0.1
        } else {
            0.0
        }
    }
}

/// Pass an obstacle on the inside when it is near an edge, else on whichever side we are.
fn swerve_direction(offset: f32, obstacle: f32) -> f32 {
    if obstacle > 0.5 {
        -1.0
    } else if obstacle < -0.5 || offset > obstacle {
        1.0
    } else {
        -1.0
    }
}

impl ApplyTrafficIndexSystem for TrafficIndexSystem {
    type Error = Infallible;

    fn on_begin_phase(
        &mut self,
        _track: &TrackState,
        grid: &mut TrafficGridState,
    ) -> Result<(), Self::Error> {
        grid.clear();
        Ok(())
    }

    fn apply_many(
        &mut self,
        track: &TrackState,
        grid: &mut TrafficGridState,
        track_positions: &[TrackPositionComponent],
        speeds: &[SpeedComponent],
        car_models: &[CarModelComponent],
    ) {
        let cars = track_positions.iter().zip(speeds).zip(car_models);
        for ((pos, speed), model) in cars {
            let car = TrafficCar {
                z: pos.z,
                offset: pos.offset,
                percent: pos.percent,
                speed: **speed,
                sprite: **model,
            };
            grid.insert(track.find(pos.z), car);
        }
    }
}

/// The segment the player's car was in when the step began. The JS original evaluates the
/// whole step against it, so all player systems do too.
fn origin_segment(track: &TrackState, origin: f32) -> &Segment {
    &track.segments[track.find(origin + player_z())]
}

impl ApplyDrivingSystem for DrivingSystem {
    type Error = Infallible;

    fn apply_single(
        &mut self,
        track: &TrackState,
        controls: &ControlsState,
        pos: &mut TrackPositionComponent,
        speed: &mut SpeedComponent,
        driver: &mut DriverComponent,
        origin: &mut StepOriginComponent,
    ) {
        let dt = STEP;
        **origin = pos.z;
        let segment = origin_segment(track, pos.z);
        let speed_percent = **speed / MAX_SPEED;
        // At top speed, crossing the road from left to right takes one second.
        let dx = dt * 2.0 * speed_percent;

        pos.z = increase(pos.z, dt * **speed, track.length());

        if controls.left {
            pos.offset -= dx;
        } else if controls.right {
            pos.offset += dx;
        }
        pos.offset -= dx * speed_percent * segment.curve * CENTRIFUGAL;

        **speed += dt
            * if controls.faster {
                ACCEL
            } else if controls.slower {
                BREAKING
            } else {
                DECEL
            };
        let off_road = pos.offset < -1.0 || pos.offset > 1.0;
        if off_road && **speed > OFF_ROAD_LIMIT {
            **speed += dt * OFF_ROAD_DECEL;
        }

        // Don't ever let the car go too far out of bounds, or exceed the top speed.
        pos.offset = pos.offset.clamp(-3.0, 3.0);
        **speed = speed.clamp(0.0, MAX_SPEED);

        let steer = if controls.left {
            -1.0
        } else if controls.right {
            1.0
        } else {
            0.0
        };
        driver.steer = if **speed > 0.0 { steer } else { 0.0 };
        driver.updown = segment.p2[0] - segment.p1[0];
    }
}

impl ApplyCollisionSystem for CollisionSystem {
    type Error = Infallible;

    fn apply_single(
        &mut self,
        track: &TrackState,
        grid: &TrafficGridState,
        origin: &StepOriginComponent,
        pos: &mut TrackPositionComponent,
        speed: &mut SpeedComponent,
    ) {
        let player_z = player_z();
        let segment = origin_segment(track, **origin);

        if pos.offset < -1.0 || pos.offset > 1.0 {
            for sprite in &segment.sprites {
                let sprite_w = sprite.source.w * sprites::SCALE;
                let side = if sprite.offset > 0.0 { 1.0 } else { -1.0 };
                let center = sprite.offset + sprite_w / 2.0 * side;
                if overlap(pos.offset, PLAYER_W, center, sprite_w, 1.0) {
                    // Stop in front of the sprite, at the front of the segment.
                    **speed = MAX_SPEED / 5.0;
                    pos.z = increase(segment.p1[1], -player_z, track.length());
                    break;
                }
            }
        }

        for car in grid.cars(segment.index) {
            if **speed > car.speed && overlap(pos.offset, PLAYER_W, car.offset, car.width(), 0.8) {
                // Bump into the car's rear and lose speed.
                **speed = car.speed * (car.speed / **speed);
                pos.z = increase(car.z, -player_z, track.length());
                break;
            }
        }
    }
}

impl ApplyLapTimerSystem for LapTimerSystem {
    type Error = Infallible;

    fn apply_single(
        &mut self,
        laps: &mut LapsState,
        pos: &TrackPositionComponent,
        origin: &StepOriginComponent,
    ) {
        let player_z = player_z();
        if pos.z <= player_z {
            return;
        }
        let crossed_start = **origin < player_z;
        if laps.current > 0.0 && crossed_start {
            laps.last_was_fastest = laps.current <= laps.fastest;
            if laps.last_was_fastest {
                laps.fastest = laps.current;
            }
            laps.last = Some(laps.current);
            laps.current = 0.0;
        } else {
            laps.current += STEP;
        }
    }
}

impl ApplyParallaxSystem for ParallaxSystem {
    type Error = Infallible;

    fn apply_single(
        &mut self,
        track: &TrackState,
        backdrop: &mut BackdropState,
        pos: &TrackPositionComponent,
        origin: &StepOriginComponent,
    ) {
        let segment = origin_segment(track, **origin);
        let scroll = segment.curve * (pos.z - **origin) / SEGMENT_LENGTH;
        backdrop.sky = increase(backdrop.sky, SKY_SPEED * scroll, 1.0);
        backdrop.hills = increase(backdrop.hills, HILL_SPEED * scroll, 1.0);
        backdrop.trees = increase(backdrop.trees, TREE_SPEED * scroll, 1.0);
    }
}

impl ApplySnapshotSystem for SnapshotSystem {
    type Error = Infallible;

    fn apply_single(
        &mut self,
        view: &mut PlayerViewState,
        pos: &TrackPositionComponent,
        speed: &SpeedComponent,
        driver: &DriverComponent,
    ) {
        *view = PlayerViewState {
            position: pos.z,
            x: pos.offset,
            speed: **speed,
            steer: driver.steer,
            updown: driver.updown,
        };
    }
}

/// Builds the world's states for a race on `track`.
pub fn race_states(track: Track) -> MainWorldStates {
    MainWorldStates {
        traffic_grid: TrafficGridState::new(track.len()),
        track,
        ..Default::default()
    }
}

/// Puts the player at the start line and scatters the AI cars around the track.
pub fn spawn_racers(world: &mut RacerWorld, rng: &mut Rng) {
    world.spawn_player_with(
        TrackPositionComponent::new(TrackPositionData::default()),
        SpeedComponent::new(0.0),
        DriverComponent::new(DriverData::default()),
        StepOriginComponent::new(0.0),
    );

    let segments = world.states.track.len();
    for _ in 0..TOTAL_CARS {
        let offset = rng.next_f32() * 0.8 * crate::track::random_side(rng);
        let z = rng.range_usize(0..segments) as f32 * SEGMENT_LENGTH;
        let sprite = sprites::CARS[rng.range_usize(0..sprites::CARS.len())];
        let spread = if sprite == sprites::SEMI { 4.0 } else { 2.0 };
        let speed = MAX_SPEED / 4.0 + rng.next_f32() * MAX_SPEED / spread;
        world.spawn_car_with(
            TrackPositionComponent::new(TrackPositionData {
                z,
                offset,
                percent: 0.0,
            }),
            SpeedComponent::new(speed),
            CarModelComponent::new(sprite),
        );
    }
}
